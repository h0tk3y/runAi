package dev.runai.android

import org.w3c.dom.Element
import org.w3c.dom.Node
import org.xml.sax.ErrorHandler
import org.xml.sax.SAXParseException
import java.io.File
import javax.xml.XMLConstants
import javax.xml.parsers.DocumentBuilder
import javax.xml.parsers.DocumentBuilderFactory

sealed interface StringResource {
    val name: String
}

/** A `<string>`. [value] is the raw XML content of the element. */
data class StringEntry(override val name: String, val value: String) : StringResource

/** A `<plurals>`. [items] maps quantity to raw XML content, in file order. */
data class PluralsEntry(override val name: String, val items: Map<String, String>) : StringResource

data class StringResourceFile(
    /** `xmlns:*` declarations of the root element, for example `xliff`. */
    val namespaces: Map<String, String>,
    val entries: List<StringResource>,
)

/** Reads and writes Android `strings.xml` files without changing the XML content of values. */
object StringResourcesXml {

    /** Reads translatable `<string>` and `<plurals>` resources. Other resource types are ignored. */
    fun parse(file: File): StringResourceFile = parse(file.readText())

    fun parse(xml: String): StringResourceFile {
        val document = newDocumentBuilder().parse(xml.byteInputStream())
        val root = document.documentElement
        require(root.tagName == "resources") { "Expected <resources> as the root element, found <${root.tagName}>." }

        val namespaces = linkedMapOf<String, String>()
        val attributes = root.attributes
        for (i in 0 until attributes.length) {
            val attribute = attributes.item(i)
            if (attribute.nodeName.startsWith("xmlns:")) namespaces[attribute.nodeName.removePrefix("xmlns:")] = attribute.nodeValue
        }

        val entries = mutableListOf<StringResource>()
        for (element in root.childElements()) {
            if (element.getAttribute("translatable") == "false") continue
            val name = element.getAttribute("name")
            if (name.isEmpty()) continue
            when (element.tagName) {
                "string" -> {
                    val value = serializeChildren(element)
                    if (value.isNotBlank() && !isReference(value)) entries += StringEntry(name, value)
                }
                "plurals" -> {
                    val items = linkedMapOf<String, String>()
                    for (item in element.childElements()) {
                        if (item.tagName == "item") items[item.getAttribute("quantity")] = serializeChildren(item)
                    }
                    if (items.isNotEmpty()) entries += PluralsEntry(name, items)
                }
            }
        }
        return StringResourceFile(namespaces, entries)
    }

    /** Writes [file] as a `strings.xml`. Values are written as they are: they must be well-formed XML fragments. */
    fun write(file: StringResourceFile, out: File) {
        out.parentFile.mkdirs()
        out.writeText(render(file))
    }

    fun render(file: StringResourceFile): String = buildString {
        append("""<?xml version="1.0" encoding="utf-8"?>""").append('\n')
        append("<!-- Generated by runAi. Do not edit: changes are overwritten. -->\n")
        append("<resources")
        file.namespaces.forEach { (prefix, uri) -> append(" xmlns:").append(prefix).append("=\"").append(escapeAttribute(uri)).append('"') }
        append(">\n")
        for (entry in file.entries) {
            when (entry) {
                is StringEntry ->
                    append("    <string name=\"").append(escapeAttribute(entry.name)).append("\">").append(entry.value).append("</string>\n")
                is PluralsEntry -> {
                    append("    <plurals name=\"").append(escapeAttribute(entry.name)).append("\">\n")
                    entry.items.forEach { (quantity, value) ->
                        append("        <item quantity=\"").append(escapeAttribute(quantity)).append("\">").append(value).append("</item>\n")
                    }
                    append("    </plurals>\n")
                }
            }
        }
        append("</resources>\n")
    }

    /** A value such as `@string/other` points to another resource and is not translated. */
    fun isReference(value: String): Boolean {
        val trimmed = value.trim()
        return (trimmed.startsWith("@") || trimmed.startsWith("?")) && trimmed.none { it.isWhitespace() }
    }

    internal fun newDocumentBuilder(): DocumentBuilder {
        val factory = DocumentBuilderFactory.newInstance()
        factory.isNamespaceAware = false
        factory.isExpandEntityReferences = false
        factory.isXIncludeAware = false
        factory.setFeature("http://apache.org/xml/features/disallow-doctype-decl", true)
        factory.setFeature(XMLConstants.FEATURE_SECURE_PROCESSING, true)
        return factory.newDocumentBuilder().apply { setErrorHandler(ThrowingErrorHandler) }
    }

    /** Throws instead of printing to stderr, which the JDK's default handler does. */
    private object ThrowingErrorHandler : ErrorHandler {
        override fun warning(exception: SAXParseException) {}
        override fun error(exception: SAXParseException): Unit = throw exception
        override fun fatalError(exception: SAXParseException): Unit = throw exception
    }

    private fun serializeChildren(element: Element): String = buildString {
        val children = element.childNodes
        for (i in 0 until children.length) appendNode(children.item(i))
    }

    private fun StringBuilder.appendNode(node: Node) {
        when (node.nodeType) {
            Node.TEXT_NODE -> append(escapeText(node.nodeValue))
            Node.CDATA_SECTION_NODE -> append("<![CDATA[").append(node.nodeValue).append("]]>")
            Node.ENTITY_REFERENCE_NODE -> append('&').append(node.nodeName).append(';')
            Node.ELEMENT_NODE -> {
                append('<').append(node.nodeName)
                val attributes = node.attributes
                for (i in 0 until attributes.length) {
                    val attribute = attributes.item(i)
                    append(' ').append(attribute.nodeName).append("=\"").append(escapeAttribute(attribute.nodeValue)).append('"')
                }
                if (node.hasChildNodes()) {
                    append('>')
                    val children = node.childNodes
                    for (i in 0 until children.length) appendNode(children.item(i))
                    append("</").append(node.nodeName).append('>')
                } else {
                    append("/>")
                }
            }
            // Comments and processing instructions are dropped.
        }
    }

    private fun Element.childElements(): List<Element> {
        val result = mutableListOf<Element>()
        val children = childNodes
        for (i in 0 until children.length) {
            val child = children.item(i)
            if (child is Element) result += child
        }
        return result
    }

    private fun escapeText(text: String): String =
        text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    private fun escapeAttribute(text: String): String =
        escapeText(text).replace("\"", "&quot;")
}
